// The disposable VM guests run the SHIPPED root broker unit
// (deploy/native/blindpass-broker.service) with the SHIPPED browser-runtime
// drop-in (deploy/examples/browser-runtime.conf), both installed byte-for-byte by
// private-helper-guest.sh. This module generates the one extra guest drop-in:
// the shipped browser ExecStart with only the workload group swapped for the
// guest agent's group and one per-run `--workload` registration appended, plus
// the explicit test-only overrides listed in GUEST_OVERRIDES. Nothing else about
// the unit (sandbox, capabilities, syscall filter, runtime directories) is
// restated or loosened here.
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';

export const SHIPPED_BROKER_UNIT = 'blindpass-broker.service';
export const SHIPPED_BROKER_DIRECTORY = '/etc/systemd/system/blindpass-broker.service.d';
export const SHIPPED_BROWSER_DROP_IN = `${SHIPPED_BROKER_DIRECTORY}/browser.conf`;
export const GUEST_DROP_IN = `${SHIPPED_BROKER_DIRECTORY}/p05-guest.conf`;
// Test-only deviations from the shipped unit, kept deliberately small:
//  Restart=no          the guests SIGKILL the broker and observe ActiveState=failed
//                      with ExecMainStatus=9 before restarting it themselves; the
//                      shipped Restart=on-failure would race that observation.
//  TimeoutStopSec=5s   a stuck broker must not stall the disposable run for 90 s.
//  RuntimeMaxSec=<n>s  a leaked broker cannot outlive the test run.
export const GUEST_OVERRIDES = Object.freeze(['Restart=no', 'TimeoutStopSec=5s', 'RuntimeMaxSec=']);
const WORKLOAD = /^[A-Za-z0-9_-]{1,128}:[A-Za-z0-9_-]{1,128}:[A-Za-z0-9_.@:-]{1,256}:\d{1,10}:[a-f0-9]{32}$/;
const GROUP = /^[a-z_][a-z0-9_-]{0,31}$/;
const invalid = () => new Error('invalid_broker_unit_configuration');

// Last non-empty ExecStart= of the shipped drop-in (the first, empty one clears the base unit's).
export function shippedExecStart(dropIn) {
  if (typeof dropIn !== 'string') throw invalid();
  const values = dropIn.split('\n').filter(line => line.startsWith('ExecStart=')).map(line => line.slice('ExecStart='.length).trim());
  // The drop-in must first clear the base unit's ExecStart, then set exactly its own.
  if (values.length !== 2 || values[0] !== '' || !values[1]) throw invalid();
  const command = values[1];
  const tokens = command.split(/\s+/);
  if (!tokens[0].startsWith('/') || tokens.some(token => /["'\\$%;|&]/.test(token))) throw invalid();
  for (const required of ['--browser-resources', '--browser-runtime']) if (!tokens.includes(required)) throw invalid();
  return tokens;
}

export function guestBrokerDropIn({ shippedDropIn, workloadGroup, workload, runtimeMaxSec }) {
  if (!GROUP.test(workloadGroup ?? '') || !WORKLOAD.test(workload ?? '') || !Number.isSafeInteger(runtimeMaxSec) || runtimeMaxSec < 30 || runtimeMaxSec > 3600) throw invalid();
  const tokens = shippedExecStart(shippedDropIn);
  const index = tokens.indexOf('--workload-group');
  if (index < 0 || index !== tokens.lastIndexOf('--workload-group') || tokens.length < index + 2 || tokens.includes('--workload')) throw invalid();
  const adapted = [...tokens]; adapted[index + 1] = workloadGroup;
  return [
    '# Generated by tests/browser-handoff/shipped-broker-unit.mjs for a disposable guest. The shipped unit and',
    '# browser-runtime drop-in are installed unchanged; ExecStart is the shipped one with the workload group',
    '# replaced and one per-run --workload appended. Restart=no is a test-only override (see GUEST_OVERRIDES).',
    '[Service]', 'ExecStart=', `ExecStart=${[...adapted, '--workload', workload].join(' ')}`,
    'Restart=no', 'TimeoutStopSec=5s', `RuntimeMaxSec=${runtimeMaxSec}s`, '',
  ].join('\n');
}

// Runs in the guest as root. `exec` is injectable for tests.
export async function startShippedBroker({ workloadGroup, workload, runtimeMaxSec, exec = (file, args) => execFileSync(file, args, { stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' }),
  read = readFile, write = writeFile } = {}) {
  // Both shipped files must have been installed by the guest bootstrap.
  const unit = await read('/etc/systemd/system/blindpass-broker.service', 'utf8');
  if (!/^ExecStart=\/usr\/libexec\/blindpass-broker /m.test(unit)) throw invalid();
  const shippedDropIn = await read(SHIPPED_BROWSER_DROP_IN, 'utf8');
  await write(GUEST_DROP_IN, guestBrokerDropIn({ shippedDropIn, workloadGroup, workload, runtimeMaxSec }), { mode: 0o644 });
  exec('systemctl', ['daemon-reload']);
  exec('systemctl', ['start', SHIPPED_BROKER_UNIT]);
  // The running unit must be the shipped one plus exactly these drop-ins.
  const fragment = exec('systemctl', ['show', '--value', '-p', 'FragmentPath', '-p', 'DropInPaths', SHIPPED_BROKER_UNIT]);
  if (!fragment.includes('/etc/systemd/system/blindpass-broker.service') || !fragment.includes(SHIPPED_BROWSER_DROP_IN) || !fragment.includes(GUEST_DROP_IN)) throw invalid();
}
